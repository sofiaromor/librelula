create extension if not exists pgcrypto;

create table if not exists public.reading_clubs (
  id bigint generated by default as identity primary key,
  owner_id uuid not null references public.profiles(id) on delete cascade,
  name text not null check (char_length(trim(name)) between 3 and 80),
  description text not null default '',
  visibility text not null default 'public' check (visibility in ('public', 'private')),
  current_book_id text references public.books(id) on delete set null,
  banner_url text not null default '',
  icon_url text not null default '',
  accent_color text not null default '#8f4b2f',
  invite_code text not null unique default upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 10)),
  next_meeting_at timestamptz,
  meeting_label text not null default 'Reunión del club',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.reading_club_members (
  id bigint generated by default as identity primary key,
  club_id bigint not null references public.reading_clubs(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  role text not null default 'member' check (role in ('owner', 'moderator', 'member')),
  status text not null default 'active' check (status in ('active', 'invited', 'pending')),
  current_chapter integer not null default 1 check (current_chapter >= 1),
  progress integer not null default 0 check (progress between 0 and 100),
  joined_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (club_id, user_id)
);

create table if not exists public.reading_club_chapters (
  id bigint generated by default as identity primary key,
  club_id bigint not null references public.reading_clubs(id) on delete cascade,
  chapter_number integer not null check (chapter_number >= 1),
  title text not null default '',
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  unique (club_id, chapter_number)
);

create table if not exists public.reading_club_posts (
  id bigint generated by default as identity primary key,
  club_id bigint not null references public.reading_clubs(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  channel text not null default 'general' check (channel in ('general', 'chapter')),
  chapter_number integer,
  content text not null default '',
  quote_text text not null default '',
  image_path text not null default '',
  contains_spoilers boolean not null default false,
  parent_post_id bigint references public.reading_club_posts(id) on delete cascade,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (
    (channel = 'general' and chapter_number is null)
    or (channel = 'chapter' and chapter_number is not null and chapter_number >= 1)
  ),
  check (char_length(trim(content)) > 0 or quote_text <> '' or image_path <> '')
);

create table if not exists public.reading_club_post_reactions (
  post_id bigint not null references public.reading_club_posts(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  reaction text not null default 'heart' check (reaction in ('heart', 'leaf')),
  created_at timestamptz not null default now(),
  primary key (post_id, user_id, reaction)
);

create table if not exists public.reading_club_meetings (
  id bigint generated by default as identity primary key,
  club_id bigint not null references public.reading_clubs(id) on delete cascade,
  title text not null default 'Reunión del club',
  starts_at timestamptz not null,
  location text not null default '',
  description text not null default '',
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now()
);

create index if not exists reading_clubs_visibility_idx
