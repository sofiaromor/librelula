create or replace function public.reading_club_add_owner()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.reading_club_members (club_id, user_id, role, status, current_chapter, progress)
  values (new.id, new.owner_id, 'owner', 'active', 1, 0)
  on conflict (club_id, user_id) do update
    set role = 'owner', status = 'active';
  return new;
end;
$$;

drop trigger if exists reading_club_add_owner_after_insert on public.reading_clubs;
create trigger reading_club_add_owner_after_insert
after insert on public.reading_clubs
for each row execute function public.reading_club_add_owner();

create or replace function public.is_reading_club_member(
  p_club_id bigint,
  p_user_id uuid default auth.uid()
)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.reading_club_members m
    where m.club_id = p_club_id
      and m.user_id = p_user_id
      and m.status = 'active'
  );
$$;

create or replace function public.is_reading_club_admin(
  p_club_id bigint,
  p_user_id uuid default auth.uid()
)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.reading_club_members m
    where m.club_id = p_club_id
      and m.user_id = p_user_id
      and m.status = 'active'
      and m.role in ('owner', 'moderator')
  );
$$;

create or replace function public.join_reading_club(
  p_club_id bigint,
  p_invite_code text default null
)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  v_club public.reading_clubs%rowtype;
begin
  if auth.uid() is null then
    raise exception 'Debes iniciar sesión para unirte a un club.';
  end if;

  select * into v_club
  from public.reading_clubs
  where id = p_club_id;

  if not found then
    raise exception 'El club no existe.';
  end if;

  if v_club.visibility = 'private'
     and upper(trim(coalesce(p_invite_code, ''))) <> upper(v_club.invite_code) then
    raise exception 'El código de invitación no es válido.';
  end if;

  insert into public.reading_club_members (club_id, user_id, role, status)
  values (p_club_id, auth.uid(), 'member', 'active')
  on conflict (club_id, user_id) do update
    set status = 'active', updated_at = now();

  return true;
end;
$$;

create or replace function public.join_reading_club_by_code(p_invite_code text)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  v_club_id bigint;
begin
  if auth.uid() is null then
    raise exception 'Debes iniciar sesión para usar una invitación.';
  end if;

  select id into v_club_id
  from public.reading_clubs
  where visibility = 'private'
    and upper(invite_code) = upper(trim(coalesce(p_invite_code, '')))
  limit 1;

  if v_club_id is null then
    raise exception 'El código de invitación no es válido.';
  end if;

  insert into public.reading_club_members (club_id, user_id, role, status)
  values (v_club_id, auth.uid(), 'member', 'active')
  on conflict (club_id, user_id) do update
    set status = 'active', updated_at = now();

  return v_club_id;
end;
$$;

create or replace function public.leave_reading_club(p_club_id bigint)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  v_role text;
begin
  if auth.uid() is null then
    raise exception 'Debes iniciar sesión.';
  end if;

  select role into v_role
  from public.reading_club_members
  where club_id = p_club_id and user_id = auth.uid();

  if v_role = 'owner' then
    raise exception 'La persona creadora no puede abandonar el club sin transferirlo.';
  end if;

  delete from public.reading_club_members
  where club_id = p_club_id and user_id = auth.uid();

  return true;
end;
$$;

create or replace function public.update_reading_club_progress(
  p_club_id bigint,
  p_current_chapter integer,
  p_progress integer
)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
begin
  if auth.uid() is null then
    raise exception 'Debes iniciar sesión.';
  end if;

  update public.reading_club_members
  set current_chapter = greatest(1, coalesce(p_current_chapter, 1)),
      progress = greatest(0, least(100, coalesce(p_progress, 0))),
      updated_at = now()
  where club_id = p_club_id
    and user_id = auth.uid()
    and status = 'active';

  if not found then
    raise exception 'No perteneces a este club.';
  end if;

  return true;
end;
$$;

