function photoUrls(isbn) {
  const suffix = isbn.slice(-2);
  const host = `https://imagessl${isbn.slice(-1)}.casadellibro.com/a/l`;
  return [`${host}/s5/${suffix}/${isbn}.webp`, `${host}/s7/${suffix}/${isbn}.webp`];
}

export const VERIFIED_PAINTED_EDGE_PRESETS = photos.map(([isbn, height, front, edge]) => {
  const [thumbnail, original] = photoUrls(isbn);
  const normalized = (points) => points.map(([x, y]) => [x / 552, y / height]);
  return {
    isbn,
    cover_urls: [thumbnail, original],
    product_image_url: original,
    image_gallery: [thumbnail, original],
    front_quad: normalized(front),
    fore_edge_quad: normalized(edge),
  };
});

