const byIsbn = new Map(VERIFIED_PAINTED_EDGE_PRESETS.map((preset) => [preset.isbn, preset]));
const byCover = new Map(VERIFIED_PAINTED_EDGE_PRESETS.flatMap((preset) => preset.cover_urls.map((url) => [url, preset])));

export function verifiedPaintedEdgePreset(isbn, cover) {
  const preset = byIsbn.get(String(isbn || "").replace(/[^0-9X]/gi, ""));
  return preset?.cover_urls.includes(cover) ? preset : null;
}

export function verifiedOriginalImage(cover) {
  return byCover.get(cover)?.product_image_url || cover;
}
